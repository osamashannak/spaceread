CREATE TABLE IF NOT EXISTS moderation.signal (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type text NOT NULL,
    target_id text NOT NULL,
    source text NOT NULL,
    attribute text NOT NULL,
    score double precision,
    threshold double precision,
    severity text,
    payload jsonb,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    CONSTRAINT moderation_signal_target_type_check
        CHECK (target_type IN (
            'professor_review',
            'review_reply',
            'review_attachment',
            'review_report',
            'course_file',
            'professor_request',
            'professor'
        ))
);

CREATE INDEX IF NOT EXISTS moderation_signal_target_created_at_index
    ON moderation.signal (target_type, target_id, created_at DESC);
